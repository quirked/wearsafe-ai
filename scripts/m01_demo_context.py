"""M01-demo Part B (demo_v0, PRELIMINARY) — PPG-DaLiA context model (D03 v1 context_5s features).

Writes splits/ppg_dalia_v1.json (LOSO over 15 subjects; automatic checks), trains LR and RF (fixed
hyperparameters, balanced class weights, fit on training folds only) on train_candidate windows with the 4 context
classes, and produces out-of-fold predictions for EVERY 5 s window (each predicted by the fold model that did not see
that subject). Writes results/<date>_M01_demo_v0/context/ and reports/M01_demo_v0_context_tables.md.
Usage (repo root):  python scripts/m01_demo_context.py [--n-jobs 20]
"""
import argparse
import hashlib
import json
import subprocess
import sys
import time
from pathlib import Path

import joblib
import numpy as np
import pandas as pd
from sklearn.ensemble import RandomForestClassifier
from sklearn.impute import SimpleImputer
from sklearn.linear_model import LogisticRegression
from sklearn.metrics import confusion_matrix, f1_score
from sklearn.pipeline import make_pipeline
from sklearn.preprocessing import StandardScaler

REPO = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(REPO / "src"))
sys.path.insert(0, str(REPO / "scripts"))
from wearsafe import features as F  # noqa: E402
from wearsafe.schemas import CONTEXT_CLASSES, FORBIDDEN_FEATURE_COLUMNS  # noqa: E402
from wearsafe.splits import check_folds, loso_folds  # noqa: E402
from d02_smoke_report import md  # noqa: E402

SEED = 0
SPLIT = REPO / "splits/ppg_dalia_v1.json"
FEAT = REPO / "data/processed/context/ppg_dalia_features_v1.parquet"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--n-jobs", type=int, default=20)
    ap.add_argument("--date", default=time.strftime("%Y-%m-%d"))
    ap.add_argument("--run", default="")
    args = ap.parse_args()
    out = REPO / f"results/{args.date}_M01_demo_v0{args.run}/context"
    out_md = REPO / "reports/M01_demo_v0_context_tables.md"
    for p in (SPLIT, out, out_md):
        if p.exists():
            raise FileExistsError(f"{p} exists; refusing to overwrite")
    df = pd.read_parquet(FEAT)
    subjects = sorted(df.subject_id.unique())
    folds = loso_folds(subjects)
    problems = check_folds(folds, subjects)
    if problems or len(subjects) != 15:
        raise RuntimeError(f"split check failed: {problems}, subjects {len(subjects)}")
    SPLIT.write_text(json.dumps({
        "name": "ppg_dalia_v1", "dataset": "ppg_dalia", "scheme": "leave_one_subject_out", "subjects": subjects,
        "folds": folds, "checks": {"subject_in_two_splits": False, "every_subject_tested_once": True},
        "features_sha256": hashlib.sha256(FEAT.read_bytes()).hexdigest(),
        "git_commit": subprocess.run(["git", "rev-parse", "HEAD"], cwd=REPO, capture_output=True, text=True).stdout.strip(),
        "created": time.strftime("%Y-%m-%d %H:%M:%S")}, indent=2))
    cols = list(F.MOTION_FEATURE_NAMES)
    assert not set(cols) & set(FORBIDDEN_FEATURE_COLUMNS)
    tc = (df.eval_role == "train_candidate").to_numpy()
    assert df.loc[tc, "context_class"].isin(CONTEXT_CLASSES).all()
    classes = list(CONTEXT_CLASSES)
    makers = {"lr": lambda: make_pipeline(SimpleImputer(strategy="median"), StandardScaler(),
                                          LogisticRegression(class_weight="balanced", max_iter=5000)),
              "rf": lambda: make_pipeline(SimpleImputer(strategy="median"),
                                          RandomForestClassifier(n_estimators=300, min_samples_leaf=2,
                                                                 class_weight="balanced_subsample", random_state=SEED,
                                                                 n_jobs=args.n_jobs))}
    (out / "models").mkdir(parents=True)
    S = ["# M01 demo_v0 — PPG-DaLiA context model tables (PRELIMINARY) — auto-generated by scripts/m01_demo_context.py\n",
         f"Split: `splits/ppg_dalia_v1.json` (LOSO, {len(subjects)} subjects, check passed). Training windows: "
         f"train_candidate ({int(tc.sum())}). Out-of-fold predictions for all {len(df)} windows.\n"]
    keep = ["window_id", "subject_id", "window_start", "window_end", "original_label", "context_class", "eval_role",
            "label_purity", "crosses_boundary", "seconds_to_nearest_boundary"]
    t0 = time.time()
    for name, make in makers.items():
        proba = np.full((len(df), len(classes)), np.nan)
        fold_of = np.full(len(df), -1)
        for f in folds:
            tr = tc & df.subject_id.isin(f["train"]).to_numpy()
            te = (df.subject_id == f["test"][0]).to_numpy()
            m = make().fit(df.loc[tr, cols], df.loc[tr, "context_class"])
            p = m.predict_proba(df.loc[te, cols])
            idx = [list(m.classes_).index(c) for c in classes]
            proba[te] = p[:, idx]
            fold_of[te] = f["fold"]
            joblib.dump({"model": m, "features": cols, "classes": classes}, out / "models" / f"{name}_fold{f['fold']:02d}.joblib",
                        compress=3)
        assert not np.isnan(proba).any() and (fold_of >= 0).all()
        res = df[keep].copy()
        for i, c in enumerate(classes):
            res[f"p_{c}"] = proba[:, i]
        res["pred_context"] = np.array(classes)[proba.argmax(axis=1)]
        res["fold"] = fold_of
        res["model"] = name
        res.to_parquet(out / f"oof_context_{name}.parquet", index=False)
        ev = res[tc]
        f1s = f1_score(ev.context_class, ev.pred_context, labels=classes, average=None)
        macro = f1_score(ev.context_class, ev.pred_context, labels=classes, average="macro")
        cm = pd.DataFrame(confusion_matrix(ev.context_class, ev.pred_context, labels=classes),
                          index=[f"true {c}" for c in classes], columns=[f"pred {c}" for c in classes])
        per = pd.DataFrame([{"subject_id": s, "macro_f1": f1_score(g.context_class, g.pred_context, labels=classes,
                                                                   average="macro", zero_division=0),
                             "accuracy": float((g.context_class == g.pred_context).mean()), "windows": len(g)}
                            for s, g in ev.groupby("subject_id")])
        S.append(f"## {name.upper()}\n")
        S.append(f"Macro-F1 (pooled out-of-fold, train_candidate windows): **{macro:.3f}**; per-subject macro-F1 "
                 f"{per.macro_f1.mean():.3f} ± {per.macro_f1.std(ddof=0):.3f}.\n")
        S.append(md(pd.DataFrame({"class": classes, "f1": np.round(f1s, 3),
                                  "support": [int((ev.context_class == c).sum()) for c in classes]})) + "\n")
        S.append("Confusion matrix (rows true, columns predicted):\n\n" + md(cm.reset_index()) + "\n")
        S.append("Per subject:\n\n" + md(per.round(3)) + "\n")
        fa = res[~tc]
        S.append("Predicted context on non-training windows (false-alert evaluation; label shown is the original "
                 "activity):\n\n" + md(pd.crosstab(fa.original_label, fa.pred_context).reset_index()) + "\n")
        print(f"{name}: macro-F1 {macro:.3f}, {time.time() - t0:.0f}s", flush=True)
    out_md.write_text("\n".join(S))


if __name__ == "__main__":
    main()
