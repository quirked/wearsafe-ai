"""M02 gap fill (EXPERIMENT, PRELIMINARY): logistic regression for e4_clipped ACC+baro and ACC+gyro, next to the existing
random-forest rows. Same data (windows_v1, features-v2 + M02 extra sensor features), splits (splits/fallalld_v1.json),
feature columns, threshold rule (inner LOSO, recall >= 0.90) and code (M01 lr() and run_model, imported unchanged).
The M01 lr pipeline fits the median imputer and scaler inside each training fold only; class_weight="balanced".
Writes results/<date>_M02_lr_gap/ (refuses to overwrite); existing M02/M01 results are only read.
Usage (repo root):  OMP_NUM_THREADS=4 python scripts/m02_lr_gap.py
"""
import json
import sys
import time
from pathlib import Path

import pandas as pd

REPO = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(REPO / "src"))
sys.path.insert(0, str(REPO / "scripts"))
from wearsafe import features as F  # noqa: E402
from m01_demo_motion import lr, run_model  # noqa: E402
from m01_demo_eval import clip_metrics, window_metrics  # noqa: E402
from m02_extra_sensors import EXTRA, KEEP, gyro_cols  # noqa: E402
from d02_smoke_report import md  # noqa: E402

M02 = REPO / "results/2026-10-12_M02_extra_sensors"
M01 = REPO / "results/2026-10-12_M01_demo_v0_run2/motion/e4_clipped_v2"
SETS = {"gyro": ("ACC+gyro", gyro_cols()), "baro": ("ACC+baro", ["baro_change", "baro_std"])}


def main():
    out = REPO / f"results/{time.strftime('%Y-%m-%d')}_M02_lr_gap"
    if out.exists():
        raise FileExistsError(f"{out} exists; refusing to overwrite")
    split = json.loads((REPO / "splits/fallalld_v1.json").read_text())
    df = pd.read_parquet(REPO / "data/processed/motion/fallalld_e4_clipped_features-v2_v1.parquet").merge(
        pd.read_parquet(EXTRA), on="window_id")
    t0 = time.time()
    for s, (nm, extra) in SETS.items():
        d = out / f"e4_clipped_{s}"
        d.mkdir(parents=True)
        cols = list(F.MOTION_FEATURE_NAMES_V2) + extra
        oof, fold_of, thr = run_model("lr", lr, df, cols, split["folds"], d, save_models=False)
        res = df[KEEP].copy()
        res["score"], res["fold"] = oof, fold_of
        res["threshold"] = res.fold.map({r["fold"]: r["threshold"] for r in thr})
        res.to_parquet(d / "oof_lr.parquet", index=False)
        (d / "thresholds_lr.json").write_text(json.dumps(thr, indent=2))
        print(f"e4_clipped {nm} LR done, {time.time() - t0:.0f}s", flush=True)

    runs = [("ACC-only (M01)", "RF", M01 / "oof_rf.parquet"), ("ACC-only (M01)", "LR", M01 / "oof_lr.parquet")]
    for s, (nm, _) in SETS.items():
        runs += [(nm, "RF", M02 / f"e4_clipped_{s}/oof_rf.parquet"), (nm, "LR", out / f"e4_clipped_{s}/oof_lr.parquet")]
    rows = []
    for nm, model, p in runs:
        d = pd.read_parquet(p)
        wm, cm, cmd = window_metrics(d), clip_metrics(d), clip_metrics(d, dedup=True)
        rows.append({"accelerometer": "e4_clipped", "sensor_set": nm, "model": model, "source": str(p.relative_to(REPO)),
                     "pr_auc": wm["pr_auc"], "roc_auc": wm["roc_auc"], "clip_fall_detect_pct": cm["clip_fall_detect_pct"],
                     "clip_false_alarm_pct": cm["clip_false_alarm_pct"], "dedup_clip_false_alarm_pct": cmd["clip_false_alarm_pct"]})
    s = pd.DataFrame(rows)
    s.to_csv(out / "summary.csv", index=False)
    (REPO / "reports/M02_lr_gap_tables.md").write_text(
        "# M02 gap fill — LR vs RF, e4_clipped (EXPERIMENT, PRELIMINARY) — auto-generated by scripts/m02_lr_gap.py\n\n"
        + md(s.drop(columns="source").round(3)) + "\n")
    print(s.drop(columns="source").round(3).to_string())


if __name__ == "__main__":
    main()
