"""D03 report tables (smoke or full): features, wrist-HR vs ECG, report-only label-edge table. No hand-typed numbers.

Reads the D03 feature parquets (<features-root>/{motion,context,physiology}/ppg_dalia_features_<tag>.parquet) and
results/<date>_D03_bvp_hr_vs_ecg_<tag>/. Writes reports/D03_ppg_dalia_<tag>_tables.md. Optional --compare-root:
an independent re-run, compared file by file (determinism). Refuses to overwrite.

Usage (repo root):  python scripts/d03_report.py --tag smoke_v1 --results results/2026-10-12_D03_bvp_hr_vs_ecg_smoke_v1
"""
import argparse
import json
import sys
from pathlib import Path

import numpy as np
import pandas as pd
import yaml

REPO = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(REPO / "src"))
sys.path.insert(0, str(REPO / "scripts"))
from wearsafe import features as F  # noqa: E402
from d02_smoke_report import md  # noqa: E402

TASKS = {"motion_2s": "motion", "context_5s": "context", "physiology_30s": "physiology"}
EDGE_FEATS = ["acc_mag_std", "jerk_mean", "dominant_freq", "spectral_entropy"]


def r(df, nd=2):
    return df.round(nd)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--tag", required=True)
    ap.add_argument("--results", required=True)
    ap.add_argument("--features-root", default="data/processed")
    ap.add_argument("--compare-root", default=None, help="out-root of an independent features re-run")
    ap.add_argument("--compare-results", default=None, help="results folder of an independent HR-vs-ECG re-run")
    args = ap.parse_args()
    out = REPO / f"reports/D03_ppg_dalia_{args.tag}_tables.md"
    if out.exists():
        raise FileExistsError(f"{out} exists; refusing to overwrite")
    cfg = yaml.safe_load(open(REPO / "config/features_v1.yaml"))
    root = REPO / args.features_root
    feats = {n: pd.read_parquet(root / d / f"ppg_dalia_features_{args.tag}.parquet") for n, d in TASKS.items()}
    res = REPO / args.results
    run = root / f"ppg_dalia_features_{args.tag}_run"
    checks = pd.DataFrame(json.loads((run / "checks.json").read_text()))
    info = json.loads((run / "run_info.json").read_text())
    S = [f"# D03 tables ({args.tag}) — auto-generated by scripts/d03_report.py\n",
         f"Inputs: Layer A `{info['layer_a']}`, Layer B `{info['layer_b']}` (windowing config "
         f"`{info['windowing_config']}`), features commit {info['git_commit'][:7]}; HR-vs-ECG `{args.results}`.\n"]

    S.append("## 1. Invariant checks\n")
    S.append(f"{int(checks.passed.sum())} of {len(checks)} checks passed.\n")
    S.append(md(checks.assign(passed=checks.passed.map({True: "pass", False: "FAIL"}))) + "\n")

    S.append("## 2. Rows and NaN rates (%) per feature\n")
    for name, df in feats.items():
        cols = list(F.PHYSIOLOGY_FEATURE_NAMES if name == "physiology_30s" else F.MOTION_FEATURE_NAMES)
        t = (df.groupby("subject_id")[cols].apply(lambda g: g.isna().mean() * 100).round(2).reset_index())
        S.append(f"**{name}** ({len(df)} rows)\n\n" + md(t) + "\n")

    S.append("## 3. Physiology (30 s): physiology_uncertain rate and SQI per activity\n")
    ph = feats["physiology_30s"]
    t = ph.groupby(["subject_id", "original_label"]).agg(
        windows=("window_id", "size"), uncertain_pct=("physiology_uncertain", lambda s: 100 * s.mean()),
        median_sqi=("ppg_sqi", "median"), median_hr=("hr_mean", "median")).reset_index()
    S.append(md(r(t)) + "\n")
    S.append(f"hr_delta NaN {ph.hr_delta.isna().mean():.2%}, hr_slope NaN {ph.hr_slope.isna().mean():.2%}, "
             f"hr_rel_baseline NaN {ph.hr_rel_baseline.isna().mean():.2%} "
             f"(of which window_start < 300 s: {(ph.window_start < 300).mean():.2%} of all windows).\n")

    S.append("## 4. Motion features per activity (median, motion_2s)\n")
    m = feats["motion_2s"]
    t = m.groupby("original_label")[["acc_mag_mean", "acc_mag_std", "jerk_mean", "dominant_freq",
                                      "spectral_entropy", "acc_saturated_frac"]].median().reset_index()
    S.append(md(r(t, 3)) + "\n")

    S.append("## 5. Wrist-PPG HR vs ECG reference — PRIMARY (8 s / 2 s reference windows)\n")
    S.append("err = BVP HR − ECG HR (bpm). coverage = % of reference windows with a BVP HR estimate "
             "(≥ 2 valid IBIs). Metrics are over covered windows. Analysis output only — never a model feature.\n")
    for f, title in (("primary_overall.csv", "Overall"), ("primary_by_subject.csv", "Per subject"),
                     ("primary_by_activity.csv", "Per activity (both subjects pooled)"),
                     ("primary_by_subject_activity.csv", "Per subject and activity"),
                     ("primary_by_sqi_bin.csv", "By SQI bin (is the SQI informative?)"),
                     ("primary_by_saturation.csv", "By fraction of saturated ACC samples in the 8 s window")):
        S.append(f"**{title}**\n\n" + md(r(pd.read_csv(res / f))) + "\n")
    pw = pd.read_csv(res / "per_window_8s.csv")
    S.append("Per-subject mean ± std of per-activity MAE: " + "; ".join(
        f"{a}: {g.mae.mean():.2f} ± {g.mae.std(ddof=0):.2f}"
        for a, g in pd.read_csv(res / "primary_by_subject_activity.csv").groupby("activity")) + "\n")
    S.append(f"Rank correlation of SQI and |err| (covered windows): "
             f"{pw[['ppg_sqi']].assign(abs_err=pw.err.abs()).dropna().corr(method='spearman').iloc[0, 1]:.3f}; "
             f"skewness SQI vs |err|: "
             f"{pw[['skew_sqi']].assign(abs_err=pw.err.abs()).dropna().corr(method='spearman').iloc[0, 1]:.3f} "
             "(report only).\n")

    S.append("## 6. SQI threshold sensitivity — REPORT ONLY (v1 threshold stays 0.9; must not be changed from this)\n")
    S.append(md(r(pd.read_csv(res / "sqi_sensitivity_report_only.csv"))) + "\n")
    t = pd.read_csv(res / "sqi_sensitivity_by_activity_report_only.csv")
    S.append("By activity (MAE / % windows kept):\n\n" + md(
        t.assign(cell=t.apply(lambda x: f"{x.mae:.1f} / {x.windows_kept_pct:.0f}%", axis=1))
        .pivot(index="activity", columns="sqi_threshold", values="cell").reset_index()) + "\n")

    S.append("## 7. SECONDARY — 30 s physiology windows (feature hr_mean vs mean ECG HR of reference windows inside)\n")
    for f, title in (("secondary_30s_by_activity.csv", "All 30 s windows, per activity"),
                     ("secondary_30s_certain_by_activity.csv", "Only windows NOT flagged physiology_uncertain"),
                     ("secondary_30s_by_subject_activity.csv", "Per subject and activity")):
        S.append(f"**{title}**\n\n" + md(r(pd.read_csv(res / f))) + "\n")

    S.append("## 8. Label-edge noise — REPORT ONLY (does NOT change the 10 s rule or any v1 training role)\n")
    edges = cfg["report_only"]["boundary_bins_s"] + [np.inf]
    labels = [f"{a:g}–{b:g} s" if np.isfinite(b) else f"{a:g}+ s" for a, b in zip(edges[:-1], edges[1:])]
    S.append("Bins of seconds_to_nearest_boundary (0 = window crosses a label change). Median feature per bin; "
             "windows are grouped by their majority label. If labels were exact, medians would not depend on the bin.\n")
    for name in ("motion_2s", "context_5s"):
        df = feats[name].copy()
        df["bin"] = pd.cut(df.seconds_to_nearest_boundary, edges, right=False, labels=labels)
        for feat in EDGE_FEATS:
            t = df.groupby(["original_label", "bin"], observed=False)[feat].median().unstack("bin")
            n = df.groupby(["original_label", "bin"], observed=False).size().unstack("bin")
            cell = t.round(3).astype(str) + " (n=" + n.astype(str) + ")"
            S.append(f"**{name}: median {feat}**\n\n" + md(cell.reset_index()) + "\n")
        t = df.groupby(["original_label", "bin"], observed=False).acc_mag_std.median().unstack("bin")
        ratio = (t.div(t[labels[-1]], axis=0)).round(2)
        S.append(f"**{name}: acc_mag_std median relative to the 40+ s bin of the same activity**\n\n"
                 + md(ratio.reset_index()) + "\n")

    if args.compare_root or args.compare_results:
        S.append("## 9. Determinism (independent re-run compared table by table)\n")
        rows = []
        if args.compare_root:
            for n, d in TASKS.items():
                p = Path(args.compare_root) / d / f"ppg_dalia_features_{args.tag}.parquet"
                rows.append((f"{d}/ppg_dalia_features_{args.tag}.parquet",
                             "identical" if pd.read_parquet(p).equals(feats[n]) else "DIFFERENT"))
        if args.compare_results:
            for f in sorted(res.glob("*.csv")):
                g = Path(args.compare_results) / f.name
                same = g.exists() and pd.read_csv(f).equals(pd.read_csv(g))
                rows.append((f"results/{f.name}", "identical" if same else "DIFFERENT"))
        S.append(md(pd.DataFrame(rows, columns=["file", "result"])) + "\n")
    out.write_text("\n".join(S))
    print(f"wrote {out}")


if __name__ == "__main__":
    main()
