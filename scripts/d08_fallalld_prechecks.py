"""D08 pre-checks on ALL FallAllD wrist records (read-only; nothing is built here).

1. Gravity check FIRST (config/fallalld_v1.yaml gravity_check). If it fails, the tables are written and the
   script exits with code 2 — the D08 run must stop.
2. Peak-time distribution of wrist falls (unclipped 32 Hz, and native 238 Hz for comparison).
3. Report-only list of fall clips whose detected peak lies outside the positive window [9, 11) (user decision 12).
4. Trial-number gaps and near-duplicate search (max normalised cross-correlation of 32 Hz |a| over all lags,
   all record pairs within each subject). Report only; nothing is excluded.

Writes reports/D08_fallalld_prechecks_tables.md (refuses to overwrite).
Usage (repo root):  python scripts/d08_fallalld_prechecks.py
"""
import json
import sys
from pathlib import Path

import numpy as np
import pandas as pd
import yaml

REPO = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(REPO / "src"))
sys.path.insert(0, str(REPO / "scripts"))
from wearsafe import fallalld_io as fio  # noqa: E402
from wearsafe import motion_harmonise as mh  # noqa: E402
from d02_smoke_report import md  # noqa: E402

OUT = REPO / "reports/D08_fallalld_prechecks_tables.md"


def xcorr_max(F, norms, i, js, n):
    """Max normalised cross-correlation (over all lags) between record i and records js (rFFT of zero-padded |a|)."""
    prod = F[i][None, :] * np.conj(F[js])
    cc = np.fft.irfft(prod, n=n, axis=1)
    return np.abs(cc).max(axis=1) / (norms[i] * norms[js])


def main():
    if OUT.exists():
        raise FileExistsError(f"{OUT} exists; refusing to overwrite")
    cfg = yaml.safe_load(open(REPO / "config/fallalld_v1.yaml"))
    gc = cfg["gravity_check"]
    w, info = fio.wrist_records(REPO)
    cpg = cfg["counts_per_g"]
    S = ["# D08 pre-checks — auto-generated by scripts/d08_fallalld_prechecks.py\n",
         f"Wrist records: {len(w)} (falls {int((w.kind == 'fall').sum())}, ADLs {int((w.kind == 'adl').sum())}), "
         f"subjects {w.subject_id.nunique()}.\n"]

    # 1. gravity check
    adl = w[w.ActivityID.between(*gc["activity_ids"])].reset_index(drop=True)
    g = mh.gravity_check(adl.Acc.tolist(), cpg, seg=int(cfg["native_hz"] * gc["segment_s"]),
                         std_lt=gc["low_motion"]["std_mag_g_lt"], range_lt=gc["low_motion"]["range_mag_g_lt"])
    lo, hi = gc["pass_range_g"]
    passed = bool(lo <= g["median_g"] <= hi and g["n_records"] >= gc["min_records"])
    adl["low_motion_median_g"] = g["per_record"]
    per_subj = adl.groupby("subject_id").low_motion_median_g.agg(
        records_with_low_motion="count", median_g="median",
        p25=lambda s: s.quantile(.25), p75=lambda s: s.quantile(.75)).reset_index()
    per_subj["outside_1±0.05"] = ~per_subj.median_g.between(lo, hi)
    vals = adl.low_motion_median_g.dropna()
    S.append("## 1. Gravity check (FIRST) — 4096 counts/g [inferred]\n")
    S.append(f"- Low-motion segment: non-overlapping {gc['segment_s']} s ({int(cfg['native_hz'] * gc['segment_s'])} "
             f"samples) of an ADL record (IDs {gc['activity_ids'][0]}–{gc['activity_ids'][1]}) with std(|a|) < "
             f"{gc['low_motion']['std_mag_g_lt']} g and max−min(|a|) < {gc['low_motion']['range_mag_g_lt']} g.\n"
             f"- ADL records: {len(adl)}; records with ≥ 1 low-motion segment: {g['n_records']}; segments: "
             f"{g['n_segments']}.\n"
             f"- **Median over records of per-record median |a|: {g['median_g']:.4f} g** "
             f"(IQR {vals.quantile(.25):.4f}–{vals.quantile(.75):.4f} g; min {vals.min():.4f}, max {vals.max():.4f}).\n"
             f"- Pass rule: within [{lo}, {hi}] g and ≥ {gc['min_records']} records → **{'PASS' if passed else 'FAIL'}**\n")
    S.append("Per subject (report only):\n\n" + md(per_subj.round(4)) + "\n")
    if not passed:
        OUT.write_text("\n".join(S + ["\n**GRAVITY CHECK FAILED — D08 STOPPED. Nothing else was computed.**\n"]))
        print(f"GRAVITY CHECK FAILED: median {g['median_g']:.4f} g, n {g['n_records']}")
        sys.exit(2)
    print(f"gravity check PASS: median {g['median_g']:.4f} g over {g['n_records']} records", flush=True)

    # unclipped 32 Hz |a| for all records (used by 2-4)
    mags32 = []
    for c in w.Acc:
        a = mh.harmonise(c, "unclipped", cpg)["acc_m_s2"]
        mags32.append(np.sqrt((a ** 2).sum(axis=1)))
    mags32 = np.array(mags32)
    if mags32.shape[1] != cfg["resample"]["samples_out"]:
        raise RuntimeError(f"unexpected resampled length {mags32.shape}")

    # 2. peak-time distribution
    fall = (w.kind == "fall").to_numpy()
    t32 = mags32[fall].argmax(axis=1) / cfg["resample"]["target_hz"]
    t238 = np.array([np.sqrt((c.astype(float) ** 2).sum(1)).argmax() / cfg["native_hz"] for c in w.Acc[fall]])
    peak_g = mags32[fall].max(axis=1) / mh.G
    S.append("## 2. Peak-time distribution, wrist falls (time of max |a| from clip start)\n")
    rows = []
    for name, t in (("unclipped 32 Hz", t32), ("native 238 Hz", t238)):
        rows.append({"signal": name, "n": len(t), **{f"p{q}": round(float(np.percentile(t, q)), 3)
                                                     for q in (1, 5, 25, 50, 75, 95, 99)},
                     "% in [9, 11)": round(100 * np.mean((t >= 9) & (t < 11)), 2),
                     "% in [9.5, 10.5)": round(100 * np.mean((t >= 9.5) & (t < 10.5)), 2),
                     "% in [9, 12)": round(100 * np.mean((t >= 9) & (t < 12)), 2)})
    S.append(md(pd.DataFrame(rows)) + "\n")
    edges = np.arange(0, 20.5, 0.5)
    h = np.histogram(t32, bins=edges)[0]
    S.append("Histogram (unclipped 32 Hz, 0.5 s bins; only non-empty bins): "
             + ", ".join(f"[{a:g},{a + 0.5:g}): {n}" for a, n in zip(edges[:-1], h) if n) + "\n")
    S.append(f"Max |t32 − t238| = {np.abs(t32 - t238).max():.3f} s; median {np.median(np.abs(t32 - t238)):.3f} s.\n")
    per = pd.DataFrame({"subject_id": w.subject_id[fall].to_numpy(), "t": t32}).groupby("subject_id").t.agg(
        falls="count", median="median", p5=lambda s: s.quantile(.05), p95=lambda s: s.quantile(.95),
        pct_in_9_11=lambda s: 100 * ((s >= 9) & (s < 11)).mean()).reset_index()
    S.append("Per subject:\n\n" + md(per.round(3)) + "\n")

    # 3. decision-12 list
    fw = w[fall].assign(peak_t_32hz=t32, peak_t_238hz=t238, peak_g_32hz=peak_g)
    out = fw[(fw.peak_t_32hz < 9) | (fw.peak_t_32hz >= 11)]
    S.append("## 3. Fall clips whose detected peak lies OUTSIDE the positive window [9, 11) — REPORT ONLY "
             "(user decision 12; any exclusion is the user's call, before any model is trained)\n")
    S.append(f"{len(out)} of {len(fw)} fall clips ({100 * len(out) / len(fw):.2f}%).\n")
    S.append(md(out[["record_id", "original_label", "peak_t_32hz", "peak_t_238hz", "peak_g_32hz"]]
                .round(3).sort_values("peak_t_32hz")) + "\n")

    # 4a. trial gaps
    S.append("## 4. Trial-number gaps and near-duplicates (report only)\n")
    grp = w.groupby(["SubjectID", "ActivityID"]).TrialNo.apply(lambda s: sorted(s.tolist()))
    gaps = []
    for (sub, act), trials in grp.items():
        if trials != list(range(1, len(trials) + 1)):
            missing = sorted(set(range(1, max(trials) + 1)) - set(trials))
            nb = {a: grp.get((sub, a), []) for a in (act - 1, act + 1)}
            typical = int(w[w.ActivityID == act].groupby("SubjectID").size().median())
            gaps.append({"subject_id": fio.record_id(sub, act, 1)[:12], "activity": f"{act}: {info[act]}",
                         "trials_present": trials, "missing": missing, "n_present": len(trials),
                         "typical_n_this_activity": typical,
                         "neighbour_trials": {a: v for a, v in nb.items() if v},
                         "neighbour_has_missing_numbers": any(set(missing) & set(v) for v in nb.values())})
    gt = pd.DataFrame(gaps)
    S.append(f"Groups with gaps: {len(gt)} of {len(grp)}. Missing trial numbers in total: "
             f"{int(gt.missing.map(len).sum())}. Groups whose present count exceeds the typical count for that "
             f"activity: {int((gt.n_present > gt.typical_n_this_activity).sum())}.\n")
    S.append(f"Missing-number pattern: max present trial among gap groups = {int(gt.trials_present.map(max).max())}; "
             f"groups missing only trial 1: {int(gt.missing.map(lambda m: m == [1]).sum())}.\n")
    S.append(md(gt.astype(str)) + "\n")

    # 4b. near-duplicates
    thr = cfg["prechecks"]["near_duplicate_xcorr_gt"]
    n = 2 * mags32.shape[1]
    dm = mags32 - mags32.mean(axis=1, keepdims=True)
    F = np.fft.rfft(dm, n=n, axis=1)
    norms = np.linalg.norm(dm, axis=1)
    pairs, best = [], []
    for sid, idx in w.groupby("subject_id").indices.items():
        idx = np.array(sorted(idx))
        for k, i in enumerate(idx[:-1]):
            js = idx[k + 1:]
            c = xcorr_max(F, norms, i, js, n)
            best.append(c.max())
            for j, v in zip(js, c):
                if v > thr:
                    pairs.append({"record_a": w.record_id[i], "record_b": w.record_id[j], "max_xcorr": round(float(v), 5),
                                  "same_activity": bool(w.ActivityID[i] == w.ActivityID[j]),
                                  "label_a": w.original_label[i], "label_b": w.original_label[j]})
    n_pairs = sum(len(v) * (len(v) - 1) // 2 for v in w.groupby("subject_id").indices.values())
    S.append(f"Near-duplicate search: {n_pairs} within-subject record pairs; max normalised cross-correlation of "
             f"de-meaned 32 Hz |a| over all lags; flag > {thr}. Flagged pairs: **{len(pairs)}**. "
             f"Distribution of each record's best match: median {np.median(best):.3f}, p99 {np.percentile(best, 99):.3f}, "
             f"max {np.max(best):.4f}.\n")
    if pairs:
        S.append(md(pd.DataFrame(pairs)) + "\n")
    gap_recs = set()
    for r in gaps:
        sub = int(r["subject_id"][-2:])
        act = int(r["activity"].split(":")[0])
        gap_recs |= set(w.record_id[(w.SubjectID == sub) & (w.ActivityID == act)])
    S.append(f"Flagged pairs involving a gap-group record: {sum(p['record_a'] in gap_recs or p['record_b'] in gap_recs for p in pairs)}.\n")
    OUT.write_text("\n".join(S))
    (REPO / "logs").mkdir(exist_ok=True)
    print(json.dumps({"gravity_median_g": g["median_g"], "n_records": g["n_records"], "pass": passed,
                      "peak_outside_9_11": len(out), "gap_groups": len(gt), "near_dup_pairs": len(pairs)}))


if __name__ == "__main__":
    main()
