"""M01-demo Part C (demo_v0, PRELIMINARY; report only) — device-discrimination check (CLAUDE.md §2.3).

Can a simple classifier tell FallAllD e4_clipped everyday (ADL) windows from PPG-DaLiA windows using the same motion
features? Both feature tables come from the same function (wearsafe.features.motion_features) on 2 s windows of
32 Hz m/s^2 ACC on the E4 1/64 g grid: FallAllD = data/processed/motion/fallalld_e4_clipped_features-v1_v1.parquet
(window_role == adl), PPG-DaLiA = data/processed/motion/ppg_dalia_features_v1.parquet (all motion_2s windows).
Subject-grouped 5-fold CV (GroupKFold), LR (simple) and RF; plus single-feature AUCs. Changes nothing.
Writes results/<date>_M01_demo_v0<run>/device_check/ and reports/M01_demo_v0_device_tables.md.
Usage (repo root):  python scripts/m01_demo_device_check.py --run _run2
"""
import argparse
import json
import sys
import time
from pathlib import Path

import numpy as np
import pandas as pd
from sklearn.ensemble import RandomForestClassifier
from sklearn.impute import SimpleImputer
from sklearn.linear_model import LogisticRegression
from sklearn.metrics import roc_auc_score
from sklearn.model_selection import GroupKFold
from sklearn.pipeline import make_pipeline
from sklearn.preprocessing import StandardScaler

REPO = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(REPO / "src"))
sys.path.insert(0, str(REPO / "scripts"))
from wearsafe import features as F  # noqa: E402
from d02_smoke_report import md  # noqa: E402


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--date", default=time.strftime("%Y-%m-%d"))
    ap.add_argument("--run", default="")
    ap.add_argument("--n-jobs", type=int, default=16)
    args = ap.parse_args()
    out = REPO / f"results/{args.date}_M01_demo_v0{args.run}/device_check"
    out_md = REPO / "reports/M01_demo_v0_device_tables.md"
    for p in (out, out_md):
        if p.exists():
            raise FileExistsError(f"{p} exists; refusing to overwrite")
    cols = list(F.MOTION_FEATURE_NAMES)
    fa = pd.read_parquet(REPO / "data/processed/motion/fallalld_e4_clipped_features-v1_v1.parquet")
    fa = fa[fa.window_role == "adl"][["subject_id"] + cols].assign(device=1)
    pd_ = pd.read_parquet(REPO / "data/processed/motion/ppg_dalia_features_v1.parquet")[["subject_id"] + cols].assign(device=0)
    d = pd.concat([fa, pd_], ignore_index=True)
    y, g = d.device.to_numpy(), d.subject_id.to_numpy()
    makers = {"lr": lambda: make_pipeline(SimpleImputer(strategy="median"), StandardScaler(),
                                          LogisticRegression(max_iter=5000)),
              "rf": lambda: make_pipeline(SimpleImputer(strategy="median"),
                                          RandomForestClassifier(n_estimators=200, min_samples_leaf=5, random_state=0,
                                                                 n_jobs=args.n_jobs))}
    res = {}
    for name, make in makers.items():
        score = np.full(len(d), np.nan)
        for tr, te in GroupKFold(n_splits=5).split(d[cols], y, g):
            score[te] = make().fit(d.loc[tr, cols], y[tr]).predict_proba(d.loc[te, cols])[:, 1]
        res[name] = float(roc_auc_score(y, score))
        print(f"{name}: AUC {res[name]:.4f}", flush=True)
    single = []
    for c in cols:
        a = roc_auc_score(y, d[c].fillna(d[c].median()))
        single.append({"feature": c, "auc": a, "separation": abs(a - 0.5) * 2,
                       "median_fallalld_adl": fa[c].median(), "median_ppg_dalia": pd_[c].median()})
    single = pd.DataFrame(single).sort_values("separation", ascending=False)
    out.mkdir(parents=True)
    single.to_csv(out / "single_feature_auc.csv", index=False)
    (out / "auc.json").write_text(json.dumps({"auc": res, "n_fallalld_adl": len(fa), "n_ppg_dalia": len(pd_),
                                              "cv": "GroupKFold(5) by subject"}, indent=2))
    S = ["# M01 demo_v0 — device-discrimination check (PRELIMINARY, report only) — auto-generated by "
         "scripts/m01_demo_device_check.py\n",
         f"FallAllD e4_clipped ADL windows: {len(fa)}; PPG-DaLiA motion_2s windows: {len(pd_)}. Same feature code, "
         "2 s windows, 32 Hz, E4 1/64 g grid. Subject-grouped 5-fold CV. AUC 0.5 = indistinguishable; 1.0 = fully "
         "separable.\n",
         md(pd.DataFrame([{"classifier": k, "AUC": round(v, 4)} for k, v in res.items()])) + "\n",
         "Single-feature AUCs (sorted by separation = |AUC − 0.5| × 2):\n",
         md(single.round(4)) + "\n"]
    out_md.write_text("\n".join(S))


if __name__ == "__main__":
    main()
