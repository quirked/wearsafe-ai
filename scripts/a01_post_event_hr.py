"""A01 (ANALYSIS ONLY): heart rate after false-alarm jolts on PPG-DaLiA (config/a01_post_event_hr.yaml).
Writes results/<date>_A01_post_event_hr/, reports/A01_tables.md, reports/figures/A01/. Refuses to overwrite.
"""
import json
import sys
import time
from pathlib import Path

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402
import numpy as np  # noqa: E402
import pandas as pd  # noqa: E402
import yaml  # noqa: E402

REPO = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(REPO / "src"))
sys.path.insert(0, str(REPO / "scripts"))
from wearsafe import fusion_v1 as fv1  # noqa: E402
from wearsafe.post_event import event_measures  # noqa: E402
from d02_smoke_report import md  # noqa: E402

F01 = REPO / "results/2026-10-12_F01_demo_v0"
F02 = REPO / "results/2026-10-12_F02_demo_v1"
OUT = REPO / "results/2026-10-12_A01_post_event_hr"
MD = REPO / "reports/A01_tables.md"
FIG = REPO / "reports/figures/A01"


def main():
    for p in (OUT, MD, FIG):
        if p.exists():
            raise FileExistsError(p)
    cfg1 = yaml.safe_load(open(REPO / "config/fusion_v1.yaml"))
    part = json.loads((REPO / "config/fusion_v1_partition.json").read_text())
    thr = json.loads((F01 / "thresholds.json").read_text())
    sel = json.loads((F02 / "selection.json").read_text())
    dec = pd.read_parquet(F01 / "ppg_dalia_decisions.parquet")
    dec = dec.merge(pd.read_parquet(F02 / "measures_ppg_dalia.parquet"), on=["subject_id", "t"], how="left")
    w8 = pd.read_csv(REPO / "results/2026-10-12_D03_bvp_hr_vs_ecg_v1/per_window_8s.csv")
    w8["end"] = w8.t_start + 8
    T = thr["motion_threshold"]
    rng = np.random.RandomState(2026)
    ev_rows, ct_rows = [], []
    for sid, d in dec.groupby("subject_id"):
        d = d.sort_values("t").reset_index(drop=True)
        # V1 tags with the F02 dev-selected parameters
        tags = {}
        for v in ("V1-tiered", "V1-change"):
            prm = sel["chosen"][v]["params"]
            ch = np.array([fv1.is_change(r, prm["tol"]) if isinstance(r["pre_ok"], (bool, np.bool_)) else False
                           for r in d[["pre_ok", "post_ok", "std_pre", "std_post", "f_pre", "f_post"]].to_dict("records")])
            tags[v], _ = fv1.decide(v, d.t.to_numpy(), d.p_motion.to_numpy(), np.full(len(d), T), prm.get("T_high"), ch,
                                    None, cfg1["refractory_s"])
        # reliable 8 s windows: SQI >= 0.9 and acc_mag_std over the window <= gate
        acc = pd.read_parquet(REPO / f"data/interim/ppg_dalia/normalized_signals_v1/{sid}/wrist_acc.parquet",
                              columns=["x", "y", "z"]).to_numpy()
        mag = np.sqrt((acc ** 2).sum(1))
        c1, c2 = np.concatenate([[0], np.cumsum(mag)]), np.concatenate([[0], np.cumsum(mag ** 2)])
        w = w8[w8.subject_id == sid].reset_index(drop=True)
        i0, i1 = (w.t_start * 32).astype(int).to_numpy(), (w.end * 32).astype(int).to_numpy()
        n = i1 - i0
        mean = (c1[i1] - c1[i0]) / n
        std = np.sqrt(np.maximum((c2[i1] - c2[i0]) / n - mean ** 2, 0))
        gate = thr["gate_threshold_loso"][sid]
        rel = (w.ppg_sqi >= 0.9).to_numpy() & (std <= gate) & np.isfinite(w.hr_bvp.to_numpy())
        ends, hw, he = w.end.to_numpy(), w.hr_bvp.to_numpy(), w.hr_ref.to_numpy()
        ev = d[d.prompt_base]
        for r, tt, tc, ts in zip(ev.itertuples(), tags["V1-tiered"][ev.index], tags["V1-change"][ev.index], ev.prompt_stillness):
            ev_rows.append({"subject_id": sid, "ta": r.t, "activity": r.activity, "tag_V1_tiered": bool(tt),
                            "tag_V1_change": bool(tc), "tag_V0_stillness": bool(ts), **event_measures(ends, hw, rel, he, r.t)})
        alarm_t = d.t[d.p_motion >= T].to_numpy()
        far = np.array([np.min(np.abs(alarm_t - t)) >= 60 if len(alarm_t) else True for t in d.t])
        for act, k in ev.activity.value_counts().items():
            pool = d[far & (d.activity == act)].t.to_numpy()
            pick = rng.choice(pool, size=min(k, len(pool)), replace=False) if len(pool) else []
            for t in np.sort(pick):
                ct_rows.append({"subject_id": sid, "ta": float(t), "activity": act, "requested": int(k),
                                **event_measures(ends, hw, rel, he, float(t))})
        print(sid, len(ev), flush=True)
    E, C = pd.DataFrame(ev_rows), pd.DataFrame(ct_rows)
    OUT.mkdir(parents=True)
    FIG.mkdir(parents=True)
    E.to_csv(OUT / "events.csv", index=False)
    C.to_csv(OUT / "controls.csv", index=False)
    S = ["# A01 tables (ANALYSIS ONLY, PRELIMINARY) — auto-generated by scripts/a01_post_event_hr.py\n"]

    def summ(df, label):
        rt = df.recovery_s
        r = {"set": label, "n": len(df), "recovered_pct": 100 * df.recovered.mean(),
             "rec_median_s": rt.median(), "rec_p25_s": rt.quantile(.25), "rec_p75_s": rt.quantile(.75), "rec_p90_s": rt.quantile(.9),
             **{f"rec_within_{b}s_pct": 100 * (rt <= b).mean() for b in (10, 20, 30, 60, 120)},
             "coverage_wrist_change_pct": 100 * df.change_wrist.notna().mean(),
             "wrist_change_median": df.change_wrist.median(), "ecg_change_median": df.change_ecg.median(),
             "ecg_fixed30_change_median": df.change_ecg_fixed30.median()}
        for x in (10, 15, 20):
            r[f"wrist_rise_ge{x}_pct"] = 100 * (df.change_wrist >= x).sum() / max(1, df.change_wrist.notna().sum())
            r[f"ecg_rise_ge{x}_pct"] = 100 * (df.change_ecg >= x).sum() / max(1, df.change_ecg.notna().sum())
            r[f"ecg_fixed30_rise_ge{x}_pct"] = 100 * (df.change_ecg_fixed30 >= x).sum() / max(1, df.change_ecg_fixed30.notna().sum())
        both = df.dropna(subset=["change_wrist", "change_ecg"])
        r["n_both"] = len(both)
        r["wrist_vs_ecg_change_mae"] = (both.change_wrist - both.change_ecg).abs().mean() if len(both) else np.nan
        r["wrist_vs_ecg_change_corr"] = both.change_wrist.corr(both.change_ecg) if len(both) > 2 else np.nan
        return r

    for part_name in ("test", "dev"):
        subs = part["ppg_dalia"][part_name]
        e, c = E[E.subject_id.isin(subs)], C[C.subject_id.isin(subs)]
        rows = [summ(e, "events (all V0-base prompts)"), summ(e[e.tag_V1_tiered], "events also prompted by Balanced (V1-tiered)"),
                summ(e[e.tag_V1_change], "events also prompted by V1-change"), summ(e[e.tag_V0_stillness], "events also prompted by V0-stillness"),
                summ(c, "matched controls")]
        t = pd.DataFrame(rows)
        diff = {"set": "events minus controls", **{k: rows[0][k] - rows[4][k] for k in rows[0] if k != "set" and isinstance(rows[0][k], (int, float)) and np.isfinite(rows[0][k]) and np.isfinite(rows[4][k])}}
        t = pd.concat([t, pd.DataFrame([diff])], ignore_index=True)
        t.to_csv(OUT / f"summary_{part_name}.csv", index=False)
        S.append(f"## {part_name.upper()} subjects: {subs}\n\nControls requested {len(e)}, drawn {len(c)}.\n\n" + md(t.round(2).T.reset_index()) + "\n")
        pa = pd.DataFrame([summ(g, a) for a, g in e.groupby("activity")])
        S.append(f"**{part_name}: events per activity**\n\n" + md(pa.round(1)[["set", "n", "recovered_pct", "rec_median_s", "rec_p90_s",
                 "coverage_wrist_change_pct", "wrist_change_median", "ecg_change_median", "ecg_fixed30_change_median",
                 "ecg_rise_ge10_pct", "ecg_rise_ge15_pct", "ecg_rise_ge20_pct", "ecg_fixed30_rise_ge15_pct", "wrist_rise_ge15_pct"]]) + "\n")
        ps = e.groupby("subject_id").agg(events=("ta", "size"), recovered_pct=("recovered", lambda s: 100 * s.mean()),
                                         rec_median_s=("recovery_s", "median"), ecg_change_median=("change_ecg", "median"))
        S.append(f"**{part_name}: per subject** (recovered % {ps.recovered_pct.mean():.1f} ± {ps.recovered_pct.std(ddof=0):.1f}; "
                 f"median recovery {ps.rec_median_s.mean():.1f} ± {ps.rec_median_s.std(ddof=0):.1f} s)\n\n" + md(ps.round(1).reset_index()) + "\n")
        if part_name == "test":
            fig, ax = plt.subplots(1, 2, figsize=(12, 4))
            ax[0].hist(e.recovery_s.dropna(), bins=np.arange(0, 122, 4), alpha=.7, label="after a false alarm")
            ax[0].hist(c.recovery_s.dropna(), bins=np.arange(0, 122, 4), alpha=.5, label="random calm moment")
            ax[0].set_xlabel("seconds until the wrist heart reading is reliable again"); ax[0].legend()
            b = e.dropna(subset=["change_wrist", "change_ecg"])
            ax[1].scatter(b.change_ecg, b.change_wrist, s=8)
            ax[1].set_xlabel("heart-rate change, chest ECG (bpm)"); ax[1].set_ylabel("heart-rate change, wrist (bpm)")
            fig.suptitle("A01 test subjects (PRELIMINARY)")
            fig.tight_layout(); fig.savefig(FIG / "a01_test_recovery_and_change.png", dpi=100); plt.close(fig)
    MD.write_text("\n".join(S))
    print("done")


if __name__ == "__main__":
    main()
